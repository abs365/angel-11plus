/**
 * Educational Increment 007E, Part 11 — Practice Activation tooling.
 *
 * Deliberately does NOT read ali_family_review itself: that table is
 * RLS-opaque to the anon key this project's scripts use (Decision 48),
 * and by design (migration 034/054) only an authenticated admin browser
 * session can read/write it. This script instead takes the approved
 * review's essential facts as explicit input (copied from what the
 * reviewer recorded in /admin-beta/review) and:
 *
 *   1. Re-verifies, against the REAL live ali_question_bank (which IS
 *      anon-readable), every item the Founder's Part 11 checklist names:
 *      content_version match, provenance acceptable, active=true,
 *      still eligibility_status='provisional' (not already promoted or
 *      rejected elsewhere).
 *   2. Refuses to generate anything if a check fails — it does not
 *      "promote anyway" on a soft warning.
 *   3. Emits a scoped, idempotent SQL migration promoting ONLY the named
 *      family's or passage's rows to practice_eligible — never a
 *      blanket update.
 *
 * Usage (not run against production in Educational Increment 007E —
 * no approved review exists yet to activate):
 *   node scripts/generate-activation-migration.mjs --target-type question_family --target-id wave1-fam-two-character --migration-number 055 --reviewer "Jane Smith" --review-date 2026-08-20
 */

import { writeFileSync } from "node:fs";

const SUPABASE_URL = "https://agxunwcdatosrmzhhuxj.supabase.co";
const ANON_KEY = process.env.ANGEL_SUPABASE_ANON_KEY ?? "";

export function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i].replace(/^--/, "");
    args[key] = argv[i + 1];
  }
  return args;
}

/**
 * Pure, testable core: given the live rows for a target and the expected
 * content_version, decides whether activation may proceed and why not if
 * it can't. Never mutates anything — callers decide what to do with the
 * result.
 */
export function checkActivationEligibility(rows, expectedContentVersion) {
  const problems = [];
  if (rows.length === 0) problems.push("No live rows found for this target.");
  for (const row of rows) {
    if (row.content_version !== expectedContentVersion) {
      problems.push(`${row.id}: content_version ${row.content_version} does not match the reviewed version ${expectedContentVersion} (content changed since review).`);
    }
    if (row.provenance !== "angel_original") {
      problems.push(`${row.id}: provenance "${row.provenance}" is not the accepted "angel_original".`);
    }
    if (!row.active) {
      problems.push(`${row.id}: active=false, cannot be promoted while inactive.`);
    }
    if (row.eligibility_status !== "provisional") {
      problems.push(`${row.id}: eligibility_status is "${row.eligibility_status}", not "provisional" — already acted on elsewhere.`);
    }
  }
  return { canActivate: problems.length === 0, problems };
}

/** Builds the exact, scoped SQL text — a pure function so it's unit-testable without a live database. */
export function buildActivationMigrationSql({ migrationNumber, targetType, targetId, reviewer, reviewDate, rowIds, isPassage }) {
  const table = isPassage ? "public.ali_passage_bank" : "public.ali_question_bank";
  const idList = rowIds.map((id) => `'${id}'`).join(", ");
  return `-- Angel Digital 11+ — Migration ${migrationNumber}
-- Educational Increment 007E — Controlled Practice Activation.
--
-- Promotes exactly the rows approved by independent educational review
-- for ${targetType} "${targetId}" (reviewer: ${reviewer}, review date: ${reviewDate}) to
-- practice_eligible. Generated by scripts/generate-activation-migration.mjs,
-- which re-verified content_version, provenance, active state and
-- eligibility_status against live production immediately before this
-- file was written — not a blanket promotion of all provisional content.
--
-- Idempotent: only rows still in 'provisional' are updated, so re-running
-- this file after it has already taken effect is a no-op.
--
-- Run this in: Supabase Dashboard > SQL Editor > New query.

begin;

update ${table}
set eligibility_status = 'practice_eligible'
where id in (${idList})
  and eligibility_status = 'provisional';

commit;
`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const { "target-type": targetType, "target-id": targetId, "migration-number": migrationNumber, reviewer, "review-date": reviewDate } = args;
  if (!targetType || !targetId || !migrationNumber || !reviewer || !reviewDate) {
    console.error("Usage: --target-type <question_family|passage> --target-id <id> --migration-number <NNN> --reviewer <name> --review-date <YYYY-MM-DD>");
    process.exit(1);
  }
  if (!ANON_KEY) {
    console.error("ANGEL_SUPABASE_ANON_KEY environment variable not set — refusing to guess or hardcode a key in this tool.");
    process.exit(1);
  }

  const isPassage = targetType === "passage";
  const table = isPassage ? "ali_passage_bank" : "ali_question_bank";
  const filterField = isPassage ? "id" : "family_id";
  const res = await fetch(
    `${SUPABASE_URL}/rest/v1/${table}?${filterField}=eq.${encodeURIComponent(targetId)}&select=id,content_version,provenance,active,eligibility_status`,
    { headers: { apikey: ANON_KEY, Authorization: `Bearer ${ANON_KEY}` } }
  );
  const rows = await res.json();
  if (!Array.isArray(rows)) {
    console.error("Could not read live content for this target:", rows);
    process.exit(1);
  }

  const expectedVersion = rows[0]?.content_version ?? 1;
  const { canActivate, problems } = checkActivationEligibility(rows, expectedVersion);
  if (!canActivate) {
    console.error("ACTIVATION BLOCKED:");
    for (const p of problems) console.error(" -", p);
    process.exit(1);
  }

  const sql = buildActivationMigrationSql({
    migrationNumber, targetType, targetId, reviewer, reviewDate,
    rowIds: rows.map((r) => r.id), isPassage,
  });
  const outPath = `supabase/migrations/${migrationNumber}_activate_${targetId.replace(/[^a-z0-9]/gi, "_")}.sql`;
  writeFileSync(outPath, sql);
  console.log(`Wrote ${outPath} — ${rows.length} row(s) ready for Founder review and application.`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
