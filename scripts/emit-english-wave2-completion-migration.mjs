import { writeFileSync } from "node:fs";
import { passages, items } from "./generate-english-wave2.mjs";

/**
 * Educational Increment 007C completion — emits migration 051, the
 * INCREMENTAL content added on top of the already-applied migration 049
 * (50 questions, 8 passages). Filters generate-english-wave2.mjs's live
 * passages/items down to only the 1 new passage and 12 new questions
 * authored during completion, so this migration never re-inserts rows
 * that are already live in production.
 */

const NEW_PASSAGE_IDS = new Set(["wave2-eng-surprise"]);
const NEW_QUESTION_IDS = new Set([
  "w2-surprise-01", "w2-surprise-02", "w2-surprise-03", "w2-surprise-04",
  "w2-sciencefair-06", "w2-sciencefair-07", "w2-stormwarning-07",
  "w2-twoletters-07", "w2-twoletters-08", "w2-pianorecital-07",
  "w2-understudy-07", "w2-longwalk-07",
]);

const newPassages = passages.filter((p) => NEW_PASSAGE_IDS.has(p.id));
const newItems = items.filter((it) => NEW_QUESTION_IDS.has(it.id));

if (newPassages.length !== NEW_PASSAGE_IDS.size) throw new Error(`Expected ${NEW_PASSAGE_IDS.size} new passages, found ${newPassages.length}`);
if (newItems.length !== NEW_QUESTION_IDS.size) throw new Error(`Expected ${NEW_QUESTION_IDS.size} new items, found ${newItems.length}`);

function pgText(s) {
  // Passage text uses $passage$ dollar-quoting (matches migration 049), so
  // no escaping is needed unless the text itself contains the literal
  // sequence "$passage$", which none of these do.
  return s;
}

let sql = `-- Angel Digital 11+ — Migration 051
-- Educational Increment 007C completion — CSSE English Wave 2 completion
-- content, applied on top of the already-live migration 049 (50
-- questions, 8 passages). Adds 1 new original Angel passage
-- ("The Surprise", genuine two-character contrast between an anxious
-- organiser and a relaxed helper) and 12 new questions, completing the
-- 60-90 authorised range (50 -> 62) and reaching the depth floors the
-- Founder's completion directive required: multi-select 3 -> 6,
-- cumulative two-character 4 -> 6, plus 3 structurally distinct new
-- sequencing sub-types (action-reconstruction, cause/effect,
-- dispersed-evidence) rather than repeating the existing 3-item
-- reorder-events pattern.
--
-- provenance = 'angel_original' throughout. eligibility_status =
-- 'provisional' for every row, matching migration 049 exactly. Nothing
-- is Mock Eligible; nothing self-certifies otherwise.
--
-- Generated by scripts/emit-english-wave2-completion-migration.mjs from
-- scripts/generate-english-wave2.mjs's live data (not hand-typed), so
-- this file is guaranteed byte-consistent with the generator's own
-- validation pass (0 duplicate IDs/questions, 0 quotation-verification
-- failures, tier conformance) at the moment it was written.
--
-- Apply via Supabase Dashboard > SQL Editor, after migration 049.

begin;

insert into public.ali_passage_bank
  (id, title, original_text, text_type, genre, word_count, reading_complexity,
   provenance, copyright_status, pathway, content_difficulty, content_version,
   eligibility_status, active, passage_family_id, review_state)
values

`;

for (const p of newPassages) {
  sql += `('${p.id}', '${p.title.replace(/'/g, "''")}',\n`;
  sql += ` $passage$${pgText(p.originalText)}$passage$,\n`;
  sql += ` '${p.textType}', '${p.genre}', ${p.wordCount}, '${p.readingComplexity}',\n`;
  sql += ` '${p.provenance}', '${p.copyrightStatus.replace(/'/g, "''")}', array['csse'], '${p.contentDifficulty}', 1, 'provisional', true,\n`;
  sql += ` '${p.passageFamily}', null);\n\n`;
}

sql += `insert into public.ali_question_bank
  (id, subject, skill, pathway, content_difficulty, question_type, estimated_time_seconds,
   prompt, explanation, mastery_threshold, learning_unit_id,
   family_id, provenance, eligibility_status, content_version, active, addresses_misconception,
   transfer_class, supporting_competencies)
values

`;

for (let i = 0; i < newItems.length; i++) {
  const it = newItems[i];
  const questionType = it.validation === "TIER6_MULTI_SELECT" ? "multiple-choice" : "short-answer";
  const passage = newPassages.find((p) => p.id === it.passageId) ?? passages.find((p) => p.id === it.passageId);

  const promptObj = {
    id: it.id, marks: it.marks, skill: it.legacySkill, question: it.question, modelAnswer: it.modelAnswer,
    passageTitle: passage.title, passageText: passage.originalText,
  };
  if (it.acceptedAnswers) promptObj.acceptedAnswers = it.acceptedAnswers;
  if (it.quotationRequired) promptObj.quotationRequired = it.quotationRequired;
  if (it.orderedAnswer) promptObj.orderedAnswer = it.orderedAnswer;
  if (it.correctOptions) promptObj.correctOptions = it.correctOptions;
  if (it.requiredSelectionCount !== null && it.requiredSelectionCount !== undefined) promptObj.requiredSelectionCount = it.requiredSelectionCount;
  promptObj.validationTier = it.validation;

  const explanation =
    `Educational Increment 007C completion. Assessment Brain ${it.qType}, primary competency ${it.competency}. ` +
    `Question family: ${it.family}. Transfer class: ${it.transferClass}. Real evidence basis: direct reading of ` +
    `CSSE-003/005/008/013 (2021/2022/2023 Main Test papers and 2023 marking scheme, Level A, Founder-Accepted), ` +
    `reconciled in Educational Increments 007A/007B/007C. Answer validation: ${it.validation}.`;

  sql += `('${it.id}', 'english', '${it.qType}', array['csse'], '${passage.contentDifficulty}', '${questionType}', 90,\n`;
  sql += ` $json$${JSON.stringify(promptObj)}$json$,\n`;
  sql += ` '${explanation.replace(/'/g, "''")}', 2, '${it.passageId}',\n`;
  sql += ` '${it.family}', 'angel_original', 'provisional', 1, true, '${it.misconception.replace(/'/g, "''")}',\n`;
  sql += ` '${it.transferClass}', null)${i === newItems.length - 1 ? ";" : ","}\n\n`;
}

sql += "commit;\n";

writeFileSync("supabase/migrations/051_english_wave2_completion_content.sql", sql);
console.log(`Wrote migration 051: ${newPassages.length} passage(s), ${newItems.length} question(s).`);
