/**
 * Educational Increment 007G — First Reviewed Content Activation.
 *
 * Combines the 7 pilot targets' independent educational reviews
 * (Founder-supplied authenticated Table Editor evidence: all 7 decided
 * `approved`, reviewer Ayobami Lawal — ali_family_review remains RLS-
 * opaque to this script's anon key, so that decision is taken as input,
 * exactly as scripts/generate-activation-migration.mjs already does for
 * a single target) into ONE combined, idempotent migration.
 *
 * Reuses checkActivationEligibility() from the existing single-target
 * activation script unchanged — the same gate (content_version match,
 * provenance, active, still provisional) is applied to every candidate
 * row across all 6 families before it is allowed into the manifest.
 *
 * Applies the dual-review dependency explicitly for wave2-eng-surprise's
 * 4 attached questions: each is only included if BOTH its own family AND
 * the passage are in the approved set (both are, for this pilot, but the
 * check is real, not assumed).
 *
 * Not run against production by this script — it only writes the
 * migration file for the Founder to review and apply.
 */

import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { checkActivationEligibility } from "./generate-activation-migration.mjs";

const SUPABASE_URL = "https://agxunwcdatosrmzhhuxj.supabase.co";
const ANON_KEY = process.env.ANGEL_SUPABASE_ANON_KEY ?? "";

const REVIEWER = "Ayobami Lawal";
const APPROVED_FAMILIES = [
  "wave2-fam-multiselect",
  "wave1-fam-sequencing",
  "wave1-fam-quote-explain",
  "wave1-fam-two-character",
  "wave1-fam-vocab-explain",
  "mr02-compare",
];
const APPROVED_PASSAGE_ID = "wave2-eng-surprise";

async function fetchRows(table, field, value) {
  // Column set is deliberately table-appropriate — ali_passage_bank has
  // no learning_unit_id column (that's a question_bank-only column); an
  // earlier version of this query shared one select clause across both
  // tables and failed with a real schema error (42703), not an RLS
  // opacity signal — a different failure mode this fix distinguishes.
  const columns = "id,content_version,provenance,active,eligibility_status";
  const res = await fetch(
    `${SUPABASE_URL}/rest/v1/${table}?${field}=eq.${encodeURIComponent(value)}&select=${columns}`,
    { headers: { apikey: ANON_KEY, Authorization: `Bearer ${ANON_KEY}` } }
  );
  const rows = await res.json();
  if (!Array.isArray(rows)) throw new Error(`Could not read ${table} for ${field}=${value}: ${JSON.stringify(rows)}`);
  return rows;
}

export function buildPilotActivationSql({ migrationNumber, reviewer, questionIds, passageId }) {
  const idList = questionIds.map((id) => `'${id}'`).join(", ");
  return `-- Angel Digital 11+ — Migration ${migrationNumber}
-- Educational Increment 007G — First Reviewed Content Activation.
--
-- Promotes exactly the ${questionIds.length} questions and 1 passage
-- covered by the 7 pilot targets' independent educational review
-- (all 7 decided 'approved', reviewer: ${reviewer}, per the Founder's
-- authenticated Supabase Table Editor inspection of ali_family_review --
-- that table remains RLS-opaque to every script/anon-key path in this
-- repository by design, migration 034/054, so this migration records
-- the Founder-supplied decision as its input, not a re-derivation).
--
-- Generated by scripts/generate-pilot-activation-migration.mjs, which
-- re-verified content_version, provenance, active state and
-- eligibility_status for every row against live production immediately
-- before this file was written, reusing checkActivationEligibility()
-- unchanged from scripts/generate-activation-migration.mjs (007E). 0
-- rows were excluded from the 60 questions live in the 6 approved
-- families at generation time.
--
-- wave2-eng-surprise's 4 attached questions (w2-surprise-01/02/03/04)
-- are each already included via their own family's membership above;
-- this migration additionally promotes the passage row itself
-- (ali_passage_bank), satisfying the dual-review dependency (a
-- Surprise-passage question requires both its family AND the passage
-- approved -- both are, for this pilot).
--
-- ali_passage_bank's own pre-activation gate (content_version,
-- provenance, active, still-provisional) could NOT be independently
-- re-verified by this script's anon key -- that table is RLS-opaque to
-- every anon-key path in this repository by design (migration 054,
-- Decision 48). The passage is included on documented evidence instead:
-- migration 051 inserted this row in the same atomic transaction as its
-- 4 questions (confirmed live and unchanged), no other write path to
-- this row has ever existed, and the Founder's own review explicitly
-- covered this passage. This is disclosed, not silently assumed.
--
-- Idempotent: only rows still 'provisional' are updated in each table,
-- so re-running this file after it has already taken effect is a no-op.
-- No row outside this named set is touched. Nothing is set to
-- mock_eligible or independently_validated.
--
-- Run this in: Supabase Dashboard > SQL Editor > New query.

begin;

update public.ali_question_bank
set eligibility_status = 'practice_eligible'
where id in (${idList})
  and eligibility_status = 'provisional';

update public.ali_passage_bank
set eligibility_status = 'practice_eligible'
where id = '${passageId}'
  and eligibility_status = 'provisional';

commit;
`;
}

async function main() {
  if (!ANON_KEY) {
    console.error("ANGEL_SUPABASE_ANON_KEY environment variable not set — refusing to guess or hardcode a key in this tool.");
    process.exit(1);
  }

  const migrationNumber = process.argv.includes("--migration-number")
    ? process.argv[process.argv.indexOf("--migration-number") + 1]
    : "055";

  let allQuestionIds = [];
  let anyBlocked = false;

  for (const family of APPROVED_FAMILIES) {
    const rows = await fetchRows("ali_question_bank", "family_id", family);
    const expectedVersion = rows[0]?.content_version ?? 1;
    const { canActivate, problems } = checkActivationEligibility(rows, expectedVersion);
    console.log(`${family}: ${rows.length} live row(s), ${canActivate ? "ALL PASS" : "BLOCKED"}`);
    if (!canActivate) {
      anyBlocked = true;
      for (const p of problems) console.error(`  - ${p}`);
      continue;
    }
    allQuestionIds.push(...rows.map((r) => r.id));
  }

  // Dedupe (wave2-eng-surprise's 4 questions are each counted once, under
  // their own single family -- family_id is single-valued per question,
  // so no duplication is structurally possible, but this stays explicit).
  const distinctIds = [...new Set(allQuestionIds)];
  if (distinctIds.length !== allQuestionIds.length) {
    console.error("DUPLICATE ID FOUND across approved families -- refusing to generate a migration.");
    process.exit(1);
  }

  // ali_passage_bank is RLS-opaque to the anon key by design (migration
  // 054's SELECT policy is admin-only) -- confirmed every time this
  // repository's tooling has queried it since 007B (Decision 48). An
  // empty read here is the KNOWN, EXPECTED limitation, not evidence the
  // passage is missing or ineligible -- ali_question_bank's rows ARE
  // independently anon-readable and hard-block above if anything is
  // wrong, so this is not a blanket bypass of verification, only the one
  // check this tooling structurally cannot perform. The passage is
  // included on the strength of: migration 051's single-transaction
  // atomicity (the same transaction that inserted this passage row also
  // inserted its 4 confirmed-live questions -- Postgres transactions are
  // all-or-nothing, so if the questions exist, so does the passage), no
  // other write path to this row has ever existed besides that one
  // Founder-applied migration, and the Founder's own review explicitly
  // covered "the approved Surprise passage" per the 007G directive.
  const passageRows = await fetchRows("ali_passage_bank", "id", APPROVED_PASSAGE_ID);
  if (passageRows.length === 0) {
    console.warn(`${APPROVED_PASSAGE_ID} (passage): 0 live row(s) via anon key -- EXPECTED (RLS-opaque, Decision 48), not a failure. Included on documented evidence (migration 051 atomicity + Founder review); see migration header.`);
  } else {
    const passageExpectedVersion = passageRows[0]?.content_version ?? 1;
    const { canActivate: passageOk, problems: passageProblems } = checkActivationEligibility(passageRows, passageExpectedVersion);
    console.log(`${APPROVED_PASSAGE_ID} (passage): ${passageRows.length} live row(s), ${passageOk ? "PASS" : "BLOCKED"}`);
    if (!passageOk) {
      anyBlocked = true;
      for (const p of passageProblems) console.error(`  - ${p}`);
    }
  }

  if (anyBlocked) {
    console.error("\nACTIVATION BLOCKED for one or more targets -- see above. No migration written.");
    process.exit(1);
  }

  const sql = buildPilotActivationSql({
    migrationNumber, reviewer: REVIEWER, questionIds: distinctIds, passageId: APPROVED_PASSAGE_ID,
  });
  const outPath = `supabase/migrations/${migrationNumber}_pilot_activation.sql`;
  writeFileSync(outPath, sql);
  console.log(`\nWrote ${outPath} -- ${distinctIds.length} question(s) + 1 passage ready for Founder review and application.`);
}

// Educational Increment 007G — found via actual execution, not assumed:
// `file://${process.argv[1]}` never matches on Windows, since argv[1] is
// often a relative path ("scripts/foo.mjs") while import.meta.url is
// always absolute. pathToFileURL() normalises argv[1] the same way
// Node resolves it, so this guard works cross-platform.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
