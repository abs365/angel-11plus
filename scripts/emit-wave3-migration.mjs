function sqlEscape(s) {
  return s.replace(/'/g, "''");
}
function skillTag(family) {
  if (family === "mr01-missing-operand") return "arithmetic";
  if (family === "mr03-coordinate" || family === "mr03-mixed-perimeter") return "geometry";
  if (family === "mr05-constrained-multiple") return "number-properties";
  if (family === "mr02-far-ratio-context") return "algebra";
  return "arithmetic";
}
function jsonForPrompt(item) {
  const obj = { id: item.id, marks: 1, skill: skillTag(item.family), answer: item.answer, question: item.question };
  if (item.workingSteps?.length) obj.workingSteps = item.workingSteps;
  return JSON.stringify(obj);
}
function pgArray(arr) {
  if (!arr || arr.length === 0) return "null";
  return `array[${arr.map((s) => `'${s}'`).join(",")}]`;
}

