/**
 * Stage 3, Increment 007 — Controlled Activation of Approved Mathematics
 * Structural Depth Content.
 *
 * Promotes exactly the 8 questions the Founder's own authenticated
 * ali_family_review evidence approved (2 targets, both decided
 * 'approved': mr01-reverse-mean, mr03-coord-combined). ali_family_review
 * remains RLS-opaque to this script's anon key by design (migration
 * 034/054, independently re-confirmed this increment), so the
 * Founder-supplied decision is taken as this script's input, exactly as
 * every prior controlled batch's generator already does (007E pilot,
 * Batches 2-4, 007T, 007X, Stage 3 Increment 005) — see Decisions
 * 79-81, 117-119, 121-122 and ALI_DECISION_LOG.md.
 *
 * Selects candidate rows by this generator's own exact, known-good 8 IDs
 * from scripts/generate-inc006-structural-depth-batch.mjs — never by
 * family_id — matching the 007X/Increment 005 precedent, so no future
 * sibling later added to either family could ever be silently swept
 * into this activation.
 *
 * Reuses checkActivationEligibility() from generate-activation-migration.mjs
 * unchanged.
 *
 * Not run against production by this script — it only writes the
 * migration file for the Founder to review and apply.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { checkActivationEligibility } from "./generate-activation-migration.mjs";
import { mathsQuestions } from "./generate-inc006-structural-depth-batch.mjs";

function loadAnonKey() {
  const envRaw = readFileSync(".env.local", "utf8");
  for (const line of envRaw.split("\n")) {
    const m = line.match(/^NEXT_PUBLIC_SUPABASE_ANON_KEY=(.*)$/);
    if (m) return m[1].trim();
  }
  throw new Error("NEXT_PUBLIC_SUPABASE_ANON_KEY not found in .env.local");
}

const ANON_KEY = loadAnonKey();
const SUPABASE_URL = "https://" + JSON.parse(Buffer.from(ANON_KEY.split(".")[1], "base64").toString("utf8")).ref + ".supabase.co";

const REVIEWER = "Founder";
const EXPECTED_QUESTION_COUNT = 8;

const APPROVED_IDS_BY_FAMILY = {};
for (const q of mathsQuestions) (APPROVED_IDS_BY_FAMILY[q.family_id] ??= []).push(q.id);

async function fetchRowsByIds(ids) {
  const columns = "id,family_id,content_version,provenance,active,eligibility_status";
  const idList = ids.map((id) => encodeURIComponent(id)).join(",");
  const res = await fetch(
    `${SUPABASE_URL}/rest/v1/ali_question_bank?id=in.(${idList})&select=${columns}&order=id`,
    { headers: { apikey: ANON_KEY, Authorization: `Bearer ${ANON_KEY}` } }
  );
  const rows = await res.json();
  if (!Array.isArray(rows)) throw new Error(`Could not read ali_question_bank for the given ids: ${JSON.stringify(rows)}`);
  return rows;
}

export function buildInc006DepthActivationSql({ migrationNumber, reviewer, questionIds }) {
  const idList = questionIds.map((id) => `'${id}'`).join(", ");
  return `-- Angel Digital 11+ — Migration ${migrationNumber}
-- Stage 3, Increment 007 — Controlled Activation of Approved Mathematics
-- Structural Depth Content.
--
-- Promotes exactly the ${questionIds.length} questions covered by the 2 approved
-- Stage 3 Mathematics Structural Depth Review targets (mr01-reverse-mean,
-- mr03-coord-combined), both decided 'approved', reviewer: ${reviewer} —
-- per the Founder's authenticated Supabase inspection of ali_family_review
-- (that table remains RLS-opaque to every script/anon-key path in this
-- repository by design, migration 034/054, independently re-confirmed
-- this increment, so this migration records the Founder-supplied decision
-- as its input, not a re-derivation — see ALI_DECISION_LOG.md Decisions
-- 79-81, 117-119, 121-122).
--
-- Generated by scripts/generate-inc006-depth-activation-migration.mjs,
-- which re-verified content_version, provenance, active state and
-- eligibility_status for every row against live production immediately
-- before this file was written, reusing checkActivationEligibility()
-- unchanged from scripts/generate-activation-migration.mjs (007E).
--
-- Selected by exact question ID, never by family_id: no other row in
-- either family is touched, and no future sibling added later to either
-- family could ever be silently swept into this activation.
--
-- Content-depth boundary (unchanged, not claimed by this migration): this
-- migration activates these 8 questions for canonical Practice. It does
-- not solve Mathematics' wider zero-parameter-variation problem (Decision
-- 116/117 Conclusion B, still open), and does not claim mr01-reverse-mean's
-- 4 rows are 4 fully independent novel experiences -- Decision 122's own
-- finding (one shared reverse-mean reasoning structure across all 4) is
-- preserved, not superseded, by activation. mr03-coord-combined's 4 rows
-- remain 4 genuinely distinct combined-transformation experiences.
--
-- Idempotent: only rows still 'provisional' are updated, so re-running
-- this file after it has already taken effect is a no-op. No row outside
-- this named set is touched. Nothing is set to mock_eligible. No content,
-- answer, working step, misconception, difficulty, family_id, provenance,
-- or content_version is changed. ali_family_review (review history) is
-- not touched by this migration.
--
-- Fails safely: if fewer than ${questionIds.length} of the named IDs are currently
-- 'provisional' (already activated elsewhere, or missing), this UPDATE
-- simply affects fewer rows rather than erroring — re-run
-- scripts/generate-inc006-depth-activation-migration.mjs to re-verify the
-- exact candidate set against live production before applying if that is
-- ever suspected.
--
-- NOT APPLIED. Run this in: Supabase Dashboard > SQL Editor > New query.

begin;

update public.ali_question_bank
set eligibility_status = 'practice_eligible'
where id in (${idList})
  and eligibility_status = 'provisional';

commit;
`;
}

async function main() {
  const migrationNumber = process.argv.includes("--migration-number")
    ? process.argv[process.argv.indexOf("--migration-number") + 1]
    : "083";

  let allQuestionIds = [];
  let anyBlocked = false;
  const byFamily = {};

  for (const [family, expectedIds] of Object.entries(APPROVED_IDS_BY_FAMILY)) {
    const rows = await fetchRowsByIds(expectedIds);
    byFamily[family] = rows.map((r) => r.id);

    const missing = expectedIds.filter((id) => !rows.some((r) => r.id === id));
    if (missing.length > 0) {
      console.error(`${family}: MISSING from production: ${missing.join(", ")}`);
      anyBlocked = true;
      continue;
    }
    const wrongFamily = rows.filter((r) => r.family_id !== family);
    if (wrongFamily.length > 0) {
      console.error(`${family}: family_id mismatch on production: ${wrongFamily.map((r) => `${r.id} -> ${r.family_id}`).join(", ")}`);
      anyBlocked = true;
      continue;
    }

    const expectedVersion = rows[0]?.content_version ?? 1;
    const { canActivate, problems } = checkActivationEligibility(rows, expectedVersion);
    console.log(`${family}: ${rows.length} live row(s), ${canActivate ? "ALL PASS" : "BLOCKED"}`);
    if (!canActivate) {
      anyBlocked = true;
      for (const p of problems) console.error(`  - ${p}`);
      continue;
    }
    allQuestionIds.push(...rows.map((r) => r.id));
  }

  const distinctIds = [...new Set(allQuestionIds)];
  if (distinctIds.length !== allQuestionIds.length) {
    console.error("DUPLICATE ID FOUND across approved families -- refusing to generate a migration.");
    process.exit(1);
  }
  if (distinctIds.length !== EXPECTED_QUESTION_COUNT) {
    console.error(`EXPECTED EXACTLY ${EXPECTED_QUESTION_COUNT} QUESTIONS, GOT ${distinctIds.length} -- refusing to generate a migration. Investigate before proceeding.`);
    process.exit(1);
  }

  if (anyBlocked) {
    console.error("\nACTIVATION BLOCKED for one or more targets -- see above. No migration written.");
    process.exit(1);
  }

  const sql = buildInc006DepthActivationSql({ migrationNumber, reviewer: REVIEWER, questionIds: distinctIds });
  const outPath = `supabase/migrations/${migrationNumber}_inc006_depth_activation.sql`;
  writeFileSync(outPath, sql);
  console.log(`\nWrote ${outPath} -- ${distinctIds.length} question(s) ready for Founder review and application.`);
  console.log("\nManifest by family:");
  for (const [fam, ids] of Object.entries(byFamily)) console.log(`  ${fam} (${ids.length}): ${ids.join(", ")}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
