/**
 * Educational Increment 007J — Controlled Review Batch 3 Activation.
 *
 * Combines the 7 Batch 3 targets' independent educational reviews
 * (Founder-supplied authenticated Table Editor evidence: all 7 decided
 * `approved`, reviewer Ayobami Lawal — ali_family_review remains RLS-
 * opaque to this script's anon key, so that decision is taken as input,
 * exactly as scripts/generate-batch2-activation-migration.mjs already
 * does for Batch 2) into ONE combined, idempotent migration.
 *
 * Reuses checkActivationEligibility() from generate-activation-migration.mjs
 * unchanged — the same gate (content_version match, provenance, active,
 * still provisional) is applied to every candidate row across all 7
 * families before it is allowed into the manifest.
 *
 * All 7 targets are Mathematics question families with no passage
 * dependency — this script only ever touches ali_question_bank, same as
 * the Batch 2 generator.
 *
 * Not run against production by this script — it only writes the
 * migration file for the Founder to review and apply.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { checkActivationEligibility } from "./generate-activation-migration.mjs";

function loadAnonKey() {
  const envRaw = readFileSync(".env.local", "utf8");
  for (const line of envRaw.split("\n")) {
    const m = line.match(/^NEXT_PUBLIC_SUPABASE_ANON_KEY=(.*)$/);
    if (m) return m[1].trim();
  }
  throw new Error("NEXT_PUBLIC_SUPABASE_ANON_KEY not found in .env.local");
}

const ANON_KEY = loadAnonKey();
const SUPABASE_URL = "https://" + JSON.parse(Buffer.from(ANON_KEY.split(".")[1], "base64").toString("utf8")).ref + ".supabase.co";

const REVIEWER = "Ayobami Lawal";
const APPROVED_FAMILIES = [
  "mr01-missing-operand",
  "mr03-coordinate",
  "mr01-measurement-conversion",
  "mr01-data-table",
  "mr04-elapsed-time",
  "mr01-average-mean",
  "mr02-nth-term",
];

async function fetchRows(family) {
  const columns = "id,content_version,provenance,active,eligibility_status";
  const res = await fetch(
    `${SUPABASE_URL}/rest/v1/ali_question_bank?family_id=eq.${encodeURIComponent(family)}&select=${columns}&order=id`,
    { headers: { apikey: ANON_KEY, Authorization: `Bearer ${ANON_KEY}` } }
  );
  const rows = await res.json();
  if (!Array.isArray(rows)) throw new Error(`Could not read ali_question_bank for family_id=${family}: ${JSON.stringify(rows)}`);
  return rows;
}

export function buildBatch3ActivationSql({ migrationNumber, reviewer, questionIds }) {
  const idList = questionIds.map((id) => `'${id}'`).join(", ");
  return `-- Angel Digital 11+ — Migration ${migrationNumber}
-- Educational Increment 007J — Controlled Review Batch 3 Activation.
--
-- Promotes exactly the ${questionIds.length} questions covered by the 7
-- Batch 3 targets' independent educational review (all 7 decided
-- 'approved', reviewer: ${reviewer}, per the Founder's authenticated
-- Supabase Table Editor inspection of ali_family_review -- that table
-- remains RLS-opaque to every script/anon-key path in this repository by
-- design, migration 034/054, so this migration records the Founder-
-- supplied decision as its input, not a re-derivation).
--
-- Generated by scripts/generate-batch3-activation-migration.mjs, which
-- re-verified content_version, provenance, active state and
-- eligibility_status for every row against live production immediately
-- before this file was written, reusing checkActivationEligibility()
-- unchanged from scripts/generate-activation-migration.mjs (007E). 0
-- rows were excluded from the 30 questions live in the 7 approved
-- families at generation time -- the full 30-question ceiling passed
-- every gate.
--
-- No passage is touched by this migration: all 7 Batch 3 families are
-- Mathematics question families with no passage dependency.
--
-- Idempotent: only rows still 'provisional' are updated, so re-running
-- this file after it has already taken effect is a no-op. No row outside
-- this named set is touched. Nothing is set to mock_eligible or
-- independently_validated. No content, answer, or family_id is changed.
-- ali_family_review (review history) is not touched by this migration.
--
-- Run this in: Supabase Dashboard > SQL Editor > New query.

begin;

update public.ali_question_bank
set eligibility_status = 'practice_eligible'
where id in (${idList})
  and eligibility_status = 'provisional';

commit;
`;
}

async function main() {
  const migrationNumber = process.argv.includes("--migration-number")
    ? process.argv[process.argv.indexOf("--migration-number") + 1]
    : "057";

  let allQuestionIds = [];
  let anyBlocked = false;
  const byFamily = {};

  for (const family of APPROVED_FAMILIES) {
    const rows = await fetchRows(family);
    byFamily[family] = rows.map((r) => r.id);
    const expectedVersion = rows[0]?.content_version ?? 1;
    const { canActivate, problems } = checkActivationEligibility(rows, expectedVersion);
    console.log(`${family}: ${rows.length} live row(s), ${canActivate ? "ALL PASS" : "BLOCKED"}`);
    if (!canActivate) {
      anyBlocked = true;
      for (const p of problems) console.error(`  - ${p}`);
      continue;
    }
    allQuestionIds.push(...rows.map((r) => r.id));
  }

  const distinctIds = [...new Set(allQuestionIds)];
  if (distinctIds.length !== allQuestionIds.length) {
    console.error("DUPLICATE ID FOUND across approved families -- refusing to generate a migration.");
    process.exit(1);
  }
  if (distinctIds.length > 30) {
    console.error(`EXPECTED AT MOST 30 QUESTIONS (the reviewed ceiling), GOT ${distinctIds.length} -- refusing to generate a migration. Investigate before proceeding.`);
    process.exit(1);
  }

  if (anyBlocked) {
    console.error("\nACTIVATION BLOCKED for one or more targets -- see above. No migration written.");
    process.exit(1);
  }

  const sql = buildBatch3ActivationSql({ migrationNumber, reviewer: REVIEWER, questionIds: distinctIds });
  const outPath = `supabase/migrations/${migrationNumber}_batch3_activation.sql`;
  writeFileSync(outPath, sql);
  console.log(`\nWrote ${outPath} -- ${distinctIds.length} question(s) ready for Founder review and application.`);
  console.log("\nManifest by family:");
  for (const [fam, ids] of Object.entries(byFamily)) console.log(`  ${fam} (${ids.length}): ${ids.join(", ")}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
