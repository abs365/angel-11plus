#!/usr/bin/env node
/**
 * Reads scratchpad/wave1_items.json (produced by
 * generate-mathematics-wave1.mjs) and emits the SQL VALUES block for
 * migration 031, so the SQL is generated from the same validated data
 * structure rather than hand-transcribed (eliminating a real class of
 * error: a hand-typed answer disagreeing with the generator's computed
 * one).
 */
import { readFileSync, writeFileSync } from "node:fs";

const items = JSON.parse(
  readFileSync(
    "C:/Users/Admin/AppData/Local/Temp/claude/C--Users-Admin/135f4c11-3911-48ce-b2ad-471be84f3f8b/scratchpad/wave1_items.json",
    "utf8"
  )
);

const FAMILY_META = {
  "mr02-sequence-rule": { skill: "QT-MR-05", competency: "MR-02", asset: "CSSE-006 Q5/Q11/Q15 (2023), CSSE-011 Q7/Q8 (2022), CSSE-016 Q21 (2021)" },
  "mr02-substitution": { skill: "QT-MR-06", competency: "MR-02", asset: "CSSE-006 Q8/Q18 (2023), CSSE-011 Q6/Q18 (2022), CSSE-016 Q6 (2021)" },
  "mr03-angle-sum": { skill: "QT-MR-07", competency: "MR-03", asset: "CSSE-006 Q7/Q12 (2023), CSSE-011 Q12/Q17 (2022), CSSE-016 Q11 (2021)" },
  "mr05-number-property": { skill: "QT-MR-11", competency: "MR-05", asset: "CSSE-006 Q10 (2023), CSSE-011 Q13 (2022), CSSE-016 (2021)" },
  "mr05-number-property-search": { skill: "QT-MR-11", competency: "MR-05", asset: "CSSE-006 Q10 (2023) only, LOW confidence sub-format, disclosed" },
};

function difficultyFor(item) {
  if (item.family === "mr02-sequence-rule") return item.id.endsWith("-fwd") ? "easy" : "medium";
  if (item.family === "mr02-substitution") return "hard";
  if (item.family === "mr03-angle-sum") return item.question.startsWith("A triangle") ? "easy" : "medium";
  if (item.family === "mr05-number-property") return "easy";
  if (item.family === "mr05-number-property-search") return "medium";
  return "medium";
}

function sqlEscape(s) {
  return s.replace(/'/g, "''");
}

function jsonForPrompt(item) {
  const obj = {
    id: item.id,
    marks: 1,
    skill: item.family.startsWith("mr02") ? "algebra" : item.family.startsWith("mr03") ? "geometry" : "number-properties",
    answer: item.answer,
    question: item.question,
  };
  if (item.workingSteps && item.workingSteps.length > 0) obj.workingSteps = item.workingSteps;
  return JSON.stringify(obj);
}

let sql = "";
for (const item of items) {
  const meta = FAMILY_META[item.family];
  const difficulty = difficultyFor(item);
  const explanation = `Educational Increment 004, Wave 1. Assessment Brain ${meta.skill}, competency ${meta.competency}. Deterministically generated by scripts/generate-mathematics-wave1.mjs (answer computed in code from the item's own parameters, not hand-typed) and validated for duplicate id/question/answer before authoring. Real evidence basis: ${meta.asset}.`;
  const misconception = item.misconception ? sqlEscape(item.misconception) : null;

  sql += `('${item.id}', 'maths', '${meta.skill}', array['csse'], '${difficulty}', 'short-answer', 60,\n`;
  sql += ` $json$${jsonForPrompt(item)}$json$,\n`;
  sql += ` '${sqlEscape(explanation)}', 2, 'wave1-${item.family}',\n`;
  sql += ` '${item.family}', 'angel_original', 'practice_eligible', 1, true, ${misconception ? `'${misconception}'` : "null"}),\n\n`;
}

writeFileSync(
  "C:/Users/Admin/AppData/Local/Temp/claude/C--Users-Admin/135f4c11-3911-48ce-b2ad-471be84f3f8b/scratchpad/wave1_values.sql",
  sql
);
console.log(`Wrote ${items.length} VALUES rows to scratchpad/wave1_values.sql`);
console.log(`Items with misconception field: ${items.filter((i) => i.misconception).length}/${items.length}`);
