// Generates the Founder-applied TEMPLATE migration 271 for English Form B completion. Writes a file only; applies nothing.
import fs from "node:fs";
import { COMPASS_ROSE_FIXES, MARKING_CONTRACT_REPAIRS, MARKER_NOTE, REPAIR_TIER, TOP_UP_ITEMS } from "../lib/ali/questionFactory/englishFormBCompletion.ts";

const src166 = fs.readFileSync("supabase/migrations/166_english_content_foundation_increment003_comprehension.sql", "utf8");
function passage(qid) {
  const start = src166.indexOf('$json${"id":"' + qid + '"');
  const end = src166.indexOf("$json$", start + 6);
  const o = JSON.parse(src166.slice(start + 6, end));
  return { text: o.passageText, title: o.passageTitle };
}
const P = {
  "eng-inc003-compassrosechallenge": passage("eng-inc003-compassrosechallenge-q01"),
  "eng-inc003-salmonnavigation": passage("eng-inc003-salmonnavigation-q01"),
};
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const skillKey = { "QT-RC-03": "meaning", "QT-RC-04": "vocabulary" };

const rows = TOP_UP_ITEMS.map((i) => {
  const body = {
    id: i.id,
    marks: i.marks,
    skill: skillKey[i.skill],
    question: i.question,
    modelAnswer: i.modelAnswer,
    passageText: P[i.passageId].text,
    passageTitle: P[i.passageId].title,
    validationTier: i.tier,
    acceptedAnswers: i.acceptedAnswers,
    ...(i.markingGuidance ? { markingGuidance: i.markingGuidance } : {}),
  };
  const slug = i.passageId.replace("eng-inc003-", "");
  const fam = `eng-fb-${i.skill.toLowerCase().replace("qt-", "qt-")}-${slug}`;
  return `(${q(i.id)}, 'english', ${q(i.skill)}, array['csse'], ${q(i.difficulty)}, 'short-answer', ${i.estimatedTimeSeconds},
 $json$${JSON.stringify(body)}$json$,
 ${q(`English Form B completion top-up. ${i.skill} on "${P[i.passageId].title}". ${i.tier === "TIER2_ACCEPTED_SET" ? "Synonym, deterministic accepted set." : "Meaning in context, manually marked, 2 marks as 1 + 1 observable elements."} Sealed candidate: needs independent human review before any promotion.`)}, 2, ${q(i.passageId)},
 ${q(fam)}, 'angel_original', 'authentic_assessment_candidate', 1, true, ${q(i.misconception)},
 ${q(i.transferClass)})`;
});

const repairIds = MARKING_CONTRACT_REPAIRS.map(q).join(", ");
const fixSql = COMPASS_ROSE_FIXES.map((f) => {
  const lines = [];
  if (f.question) lines.push(`update public.ali_question_bank set prompt = jsonb_set(prompt, '{question}', to_jsonb(${q(f.question)}::text)) where id = ${q(f.id)};`);
  if (f.addAccepted)
    lines.push(`update public.ali_question_bank set prompt = jsonb_set(prompt, '{acceptedAnswers}', (select coalesce(jsonb_agg(distinct v), '[]'::jsonb) from jsonb_array_elements_text((prompt->'acceptedAnswers') || ${q(JSON.stringify(f.addAccepted))}::jsonb) v)) where id = ${q(f.id)};`);
  return `-- ${f.id}: ${f.reason}\n${lines.join("\n")}`;
}).join("\n\n");

const out = `-- Angel Digital 11+ — Migration 271 (TEMPLATE, NOT APPLIED; Founder decision required)
-- CSSE English Form B completion. Generated by scripts/generate-english-form-b-completion-migration.mjs from
-- lib/ali/questionFactory/englishFormBCompletion.ts (the reviewed source). Nothing here is applied automatically.
--
-- What it does (and nothing else):
--   1. MARKING CONTRACT REPAIR. The eight free-text explanation items of "The Fossil Hunter of Lyme Regis" and
--      "Two Different Projects" (Q3-Q6 of each) were registered as TIER2 accepted-answer sets, which wrongly rejects valid
--      explanations and cannot judge quality. They move to ${REPAIR_TIER}; the database already forces
--      TIER3/TIER5 items to requires_manual_marking. The existing accepted answers stay as marker support only.
--   2. COMPASS ROSE FIXES from the independent review (Q5 wording; Q2 accepted-set additions).
--   3. SIX SEALED TOP-UP ITEMS (8 marks): 2 x RC-03 and 4 x RC-04, as authentic_assessment_candidate rows.
-- It does NOT mark anything independently_validated or mock_eligible, does not compose or activate Form B, does not
-- touch Practice, and makes no assumption about an official CSSE mark split.

do $do$
begin
  -- 1. marking contract repair (candidate rows only)
  update public.ali_question_bank
     set prompt = jsonb_set(jsonb_set(prompt, '{validationTier}', to_jsonb(${q(REPAIR_TIER)}::text)), '{markerNote}', to_jsonb(${q(MARKER_NOTE)}::text))
   where id in (${repairIds})
     and eligibility_status = 'authentic_assessment_candidate';

  -- 2. Compass Rose fixes
${fixSql.split("\n").map((l) => "  " + l).join("\n")}
end $do$;

-- 3. six sealed top-up items
insert into public.ali_question_bank
  (id, subject, skill, pathway, content_difficulty, question_type, estimated_time_seconds,
   prompt, explanation, mastery_threshold, learning_unit_id,
   family_id, provenance, eligibility_status, content_version, active, addresses_misconception,
   transfer_class)
values
${rows.join(",\n")}
on conflict (id) do nothing;
`;
// Migration 271 has been APPLIED (do not rerun). This generator now writes a comparison copy only and never touches supabase/migrations.
fs.mkdirSync("scripts/output/form-b-applied-sources", { recursive: true });
fs.writeFileSync("scripts/output/form-b-applied-sources/271_regenerated_FOR_COMPARISON_ONLY.sql", out);
console.log("written", out.length, "chars;", rows.length, "rows;", MARKING_CONTRACT_REPAIRS.length, "repairs");
