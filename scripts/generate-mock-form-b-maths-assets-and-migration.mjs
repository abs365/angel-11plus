// Generates (a) the three exact static SVG figures for the sealed Form B Maths items and (b) the Founder-applied TEMPLATE
// migration 272. Writes files only; applies and publishes nothing.
import fs from "node:fs";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { AngleFigureStimulus } from "../components/mockAttempt/AngleFigureStimulus.tsx";
import { CoordinateGridStimulus } from "../components/mockAttempt/CoordinateGridStimulus.tsx";
import { FORM_B_MATHS_ITEMS, FB_STRAIGHT_LINE, FB_REFLECTION, lShapeSvg } from "../lib/ali/questionFactory/mockFormBMathsItems.ts";
import { FORM_B_REVALIDATION } from "../lib/ali/questionFactory/mockFormBRevalidation.ts";

const OUT_DIR = "public/mock-assets/formb-maths";
fs.mkdirSync(OUT_DIR, { recursive: true });

const COLOURS = {
  "var(--angel-ink)": "#1d2b44",
  "var(--angel-blue)": "#2457c5",
  "var(--angel-border)": "#d9d4c7",
  "var(--angel-sky)": "#eaf0fb",
  "var(--angel-paper)": "#ffffff",
  "var(--angel-muted)": "#51607a",
};
function standalone(markup) {
  const m = markup.match(/<svg[\s\S]*?<\/svg>/);
  let svg = m[0].replace(/ class="[^"]*"/g, "");
  for (const [k, v] of Object.entries(COLOURS)) svg = svg.split(k).join(v);
  const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  svg = svg.replace("<svg ", `<svg xmlns="http://www.w3.org/2000/svg" width="${vb[1]}" height="${vb[2]}" font-family="Arial, sans-serif" `);
  return svg.replace(/(<svg[^>]*>)/, `$1<rect width="${vb[1]}" height="${vb[2]}" fill="#ffffff"/>`);
}
const files = {
  "mock-fb-mr07-angles-01.svg": standalone(renderToStaticMarkup(React.createElement(AngleFigureStimulus, { stimulus: FB_STRAIGHT_LINE }))),
  "mock-fb-mr08-reflect-01.svg": standalone(renderToStaticMarkup(React.createElement(CoordinateGridStimulus, { stimulus: FB_REFLECTION }))),
  "mock-fb-mr07-lshape-01.svg": lShapeSvg(),
};
for (const [f, svg] of Object.entries(files)) fs.writeFileSync(`${OUT_DIR}/${f}`, svg);

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const masteryByDiff = { easy: 2, medium: 2, hard: 3 };
const rows = FORM_B_MATHS_ITEMS.map((it) => {
  const body = { id: it.id, marks: 1, skill: it.pskill, answer: it.answer, question: it.question, workingSteps: it.workingSteps };
  if (it.figure) body.stimulus = { type: "image", imageAssetUrl: `/mock-assets/formb-maths/${it.figure.file}`, altText: it.figure.altText, ...(it.figure.caption ? { caption: it.figure.caption } : {}) };
  if (it.table) body.stimulus = it.table;
  return `(${q(it.id)}, 'maths', ${q(it.skill)}, array['csse'], ${q(it.difficulty)}, 'short-answer', ${it.estimatedTimeSeconds},
 $json$${JSON.stringify(body)}$json$,
 ${q(`CSSE Maths Form B top-up (sealed). ${it.skill}. Deterministic single answer; independently re-derived in tests. Needs independent human validation before any promotion.`)}, ${masteryByDiff[it.difficulty]}, ${q(it.id)},
 ${q(it.family)}, 'angel_original', 'authentic_assessment_candidate', 1, true, ${q(it.misconception)},
 ${q(it.transferClass)})`;
});

const defects = FORM_B_REVALIDATION.filter((e) => e.defect?.repairedAnswer);
const repairSql = defects.map((e) => `  -- ${e.id}: ${e.defect.description}\n  update public.ali_question_bank set prompt = jsonb_set(prompt, '{answer}', to_jsonb(${q(e.defect.repairedAnswer)}::text)) where id = ${q(e.id)} and prompt->>'answer' = ${q(e.storedAnswer)};`).join("\n");

const out = `-- Angel Digital 11+ — Migration 272 (TEMPLATE, NOT APPLIED; Founder decision required)
-- CSSE Mathematics Form B completion. Generated by scripts/generate-mock-form-b-maths-assets-and-migration.mjs from
-- lib/ali/questionFactory/mockFormBMathsItems.ts and mockFormBRevalidation.ts (the reviewed sources).
--
-- What it does (and nothing else):
--   1. Repairs the marking-contract defect found in the revalidation of the 32 existing items.
--   2. Adds the 24 missing SEALED Form B items as authentic_assessment_candidate rows (ids and families prefixed mock-fb-).
-- It does NOT promote anything to mock_eligible or independently_validated, never touches Practice, does not compose,
-- freeze, register or activate Form B, and assumes no official CSSE mark structure. Three items reference static figures
-- under /mock-assets/formb-maths/ (generated deterministically; committed with this template).

do $do$
begin
${repairSql}
end $do$;

insert into public.ali_question_bank
  (id, subject, skill, pathway, content_difficulty, question_type, estimated_time_seconds,
   prompt, explanation, mastery_threshold, learning_unit_id,
   family_id, provenance, eligibility_status, content_version, active, addresses_misconception,
   transfer_class)
values
${rows.join(",\n")}
on conflict (id) do nothing;
`;
// Migration 272 has been APPLIED (do not rerun). This generator now writes a comparison copy only and never touches supabase/migrations.
fs.mkdirSync("scripts/output/form-b-applied-sources", { recursive: true });
fs.writeFileSync("scripts/output/form-b-applied-sources/272_regenerated_FOR_COMPARISON_ONLY.sql", out);
console.log("written", Object.keys(files).length, "figures;", rows.length, "rows;", defects.length, "repairs");
