// Generates the Founder-applied TEMPLATE migration 273: the sealed replacement passage and its 11 questions for English Form B,
// a pending-review registration for it, and the retirement of Salmon as rejected/replaced evidence (deactivated, never deleted).
// Writes a file only; applies nothing. Source of truth: lib/ali/questionFactory/englishFormBReplacement.ts.
import fs from "node:fs";
import { REPLACEMENT_ITEMS, REPLACEMENT_PASSAGE_ID, REPLACEMENT_PASSAGE_TEXT, REPLACEMENT_PASSAGE_TITLE } from "../lib/ali/questionFactory/englishFormBReplacement.ts";

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const wordCount = REPLACEMENT_PASSAGE_TEXT.split(/\s+/).filter(Boolean).length;
const SALMON = "eng-inc003-salmonnavigation";

const rows = REPLACEMENT_ITEMS.map((i) => {
  const body = {
    id: i.id, marks: i.marks, skill: i.skillLabel, question: i.question, modelAnswer: i.modelAnswer,
    passageText: REPLACEMENT_PASSAGE_TEXT, passageTitle: REPLACEMENT_PASSAGE_TITLE, validationTier: i.tier,
    ...(i.acceptedAnswers ? { acceptedAnswers: i.acceptedAnswers } : {}),
    ...(i.quotationRequired ? { quotationRequired: i.quotationRequired } : {}),
    ...(i.orderedAnswer ? { orderedAnswer: i.orderedAnswer } : {}),
    ...(i.markingGuidance ? { markingGuidance: i.markingGuidance } : {}),
  };
  const slug = REPLACEMENT_PASSAGE_ID.replace("eng-fb-", "");
  return `(${q(i.id)}, 'english', ${q(i.skill)}, array['csse'], ${q(i.difficulty)}, 'short-answer', ${i.estimatedTimeSeconds},
 $json$${JSON.stringify(body)}$json$,
 ${q(`English Form B replacement passage "${REPLACEMENT_PASSAGE_TITLE}" (replaces the rejected Salmon passage). ${i.skill}. Sealed candidate: needs independent human validation before any promotion.`)}, 2, ${q(REPLACEMENT_PASSAGE_ID)},
 ${q(`eng-fb-${i.skill.toLowerCase()}-${slug}`)}, 'angel_original', 'authentic_assessment_candidate', 1, true, ${q(i.misconception)},
 ${q(i.transferClass)})`;
});

const out = `-- Angel Digital 11+ — Migration 273 — APPLIED to production by the Founder (2026-10-09, with the approved Q10 wording). DO NOT RERUN.
-- Read-only verification (blocks A to L, line-ending-neutral passage check): see ANGEL_CSSE_MIGRATION_273_FOUNDER_PACKAGE.md. Header edited after application; the statements below are byte-for-byte what was applied.
-- English Form B: ORIGINAL replacement passage for the rejected Salmon passage. Generated by
-- scripts/generate-english-form-b-replacement-migration.mjs from lib/ali/questionFactory/englishFormBReplacement.ts.
--
-- What it does (and nothing else):
--   1. Adds the passage "${REPLACEMENT_PASSAGE_TITLE}" (${wordCount} words) and its 11 questions (18 marks) as authentic_assessment_candidate rows,
--      sealed from Practice, original content, no external rights holder.
--   2. Registers the passage for independent human review (pending_independent_review).
--   3. Records Salmon as REJECTED and REPLACED (Founder decision, 2026-10-08) and DEACTIVATES its passage and question rows so it
--      cannot be selected. Nothing is deleted: the rows stay as rejected/replaced evidence. The code-level guard
--      (lib/ali/rejectedMockContent.ts) independently refuses Salmon in the Mock composer and manifest validator.
-- It does NOT mark anything independently_validated, mock_eligible or practice_eligible, does not compose, freeze, register or
-- activate Form B, and touches no Practice content.

begin;

insert into public.ali_passage_bank
  (id, title, original_text, text_type, genre, word_count, reading_complexity,
   provenance, copyright_status, pathway, content_difficulty, content_version,
   eligibility_status, active, passage_family_id, review_state)
values
(${q(REPLACEMENT_PASSAGE_ID)}, ${q(REPLACEMENT_PASSAGE_TITLE)},
 $passage$${REPLACEMENT_PASSAGE_TEXT}$passage$,
 'informational', 'historical-explanation', ${wordCount}, 'moderate',
 'angel_original', 'Angel original, unpublished; no external rights holder', array['csse'], 'medium', 1,
 'authentic_assessment_candidate', true, ${q(REPLACEMENT_PASSAGE_ID)}, null)
on conflict (id) do nothing;

insert into public.ali_question_bank
  (id, subject, skill, pathway, content_difficulty, question_type, estimated_time_seconds,
   prompt, explanation, mastery_threshold, learning_unit_id,
   family_id, provenance, eligibility_status, content_version, active, addresses_misconception,
   transfer_class)
values
${rows.join(",\n")}
on conflict (id) do nothing;

do $do$
begin
  -- 2. pending independent review for the replacement passage
  insert into public.ali_family_review (review_target_type, family_id, reviewer, decision, notes, review_type)
  select 'passage', ${q(REPLACEMENT_PASSAGE_ID)}, 'UNASSIGNED', 'pending_independent_review'::public.family_review_decision,
    ${q(`CSSE English Form B replacement: passage "${REPLACEMENT_PASSAGE_TITLE}" + its 11-question set (${REPLACEMENT_ITEMS.map((i) => i.id.split("-").pop()).join(", ")}). Replaces the rejected Salmon passage. Independent human validation required before any promotion.`)},
    'mock_english_passage_independent_review'
  where not exists (
    select 1 from public.ali_family_review
    where family_id = ${q(REPLACEMENT_PASSAGE_ID)} and decision = 'pending_independent_review' and review_type = 'mock_english_passage_independent_review'
  );

  -- 3. Salmon: rejected and replaced evidence
  insert into public.ali_family_review (review_target_type, family_id, reviewer, decision, notes, review_type)
  select 'passage', ${q(SALMON)}, 'Founder (decision of 2026-10-08, recorded from the Founder instruction)', 'rejected'::public.family_review_decision,
    ${q(`REJECTED AND REPLACED for English Form B (Founder, 2026-10-08): structural overlap with the live bee Timed Section (shared 8-word sentence frames, same topic and arc, matching question formats, shared worked-example vocabulary). Replaced by ${REPLACEMENT_PASSAGE_ID}. Preserved as evidence; must not return to Form B. See ANGEL_CSSE_SALMON_BEE_DECISION.md.`)},
    'mock_english_passage_independent_review'
  where not exists (
    select 1 from public.ali_family_review
    where family_id = ${q(SALMON)} and decision = 'rejected' and review_type = 'mock_english_passage_independent_review'
  );

  update public.ali_passage_bank set active = false
   where id = ${q(SALMON)} and eligibility_status = 'authentic_assessment_candidate';
  update public.ali_question_bank set active = false
   where learning_unit_id = ${q(SALMON)} and eligibility_status = 'authentic_assessment_candidate';
end $do$;

commit;
`;
fs.writeFileSync("supabase/migrations/273_english_form_b_salmon_replacement_APPLIED_DO_NOT_RERUN.sql", out);
console.log("written", out.length, "chars;", rows.length, "questions;", wordCount, "words");
