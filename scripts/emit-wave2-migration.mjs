import { readFileSync, writeFileSync } from "node:fs";

const items = JSON.parse(
  readFileSync(
    "C:/Users/Admin/AppData/Local/Temp/claude/C--Users-Admin/135f4c11-3911-48ce-b2ad-471be84f3f8b/scratchpad/wave2_items.json",
    "utf8"
  )
);

const FAMILY_META = {
  "mr02-compare": { skill: "QT-MR-06", asset: "CSSE-006 Q8/Q18 (2023), CSSE-011 Q6/Q18 (2022), CSSE-016 Q6 (2021)" },
  "mr03-classify": { skill: "QT-MR-07", asset: "CSSE-006 Q7/Q12 (2023), CSSE-011 Q12/Q17 (2022), CSSE-016 Q11 (2021)" },
  "mr04-far-percent": { skill: "QT-MR-04", asset: "CSSE-006 Q1/Q13 (2023), CSSE-011 Q1/Q2/Q3 (2022), CSSE-016 Q1/Q2 (2021)" },
  "mr04-mixed-divisibility": { skill: "QT-MR-13", asset: "CSSE-006, CSSE-016 (QT-MR-13, Best-Value/Combinatorial Word Problem)" },
};

function sqlEscape(s) {
  return s.replace(/'/g, "''");
}

function jsonForPrompt(item) {
  const skillTag =
    item.family === "mr02-compare" ? "algebra" : item.family === "mr03-classify" ? "geometry" : item.family === "mr04-far-percent" ? "percentage" : "number-properties";
  const obj = { id: item.id, marks: 1, skill: skillTag, answer: item.answer, question: item.question };
  if (item.workingSteps && item.workingSteps.length > 0) obj.workingSteps = item.workingSteps;
  return JSON.stringify(obj);
}

function pgArray(arr) {
  if (!arr || arr.length === 0) return "null";
  return `array[${arr.map((s) => `'${s}'`).join(",")}]`;
}

let sql = "";
for (const item of items) {
  const meta = FAMILY_META[item.family];
  const explanation = `Educational Increment 005B, Wave 2. Assessment Brain ${meta.skill}, primary competency ${item.primaryCompetency}${
    item.supportingCompetencies.length > 0 ? `, supporting ${item.supportingCompetencies.join("/")}` : ""
  }. Structure: ${item.structure}. Transfer class: ${item.transferClass}. Deterministically generated by scripts/generate-mathematics-wave2.mjs and validated for duplicate id/question/answer before authoring. Real evidence basis: ${meta.asset}.`;
  const misconception = item.misconception ? sqlEscape(item.misconception) : null;

  sql += `('${item.id}', 'maths', '${meta.skill}', array['csse'], 'medium', 'short-answer', 60,\n`;
  sql += ` $json$${jsonForPrompt(item)}$json$,\n`;
  sql += ` '${sqlEscape(explanation)}', 2, 'wave2-${item.family}',\n`;
  sql += ` '${item.family}', 'angel_original', 'provisional', 1, true, ${misconception ? `'${misconception}'` : "null"},\n`;
  sql += ` '${item.transferClass}', ${pgArray(item.supportingCompetencies)}),\n\n`;
}

writeFileSync(
  "C:/Users/Admin/AppData/Local/Temp/claude/C--Users-Admin/135f4c11-3911-48ce-b2ad-471be84f3f8b/scratchpad/wave2_values.sql",
  sql
);
console.log(`Wrote ${items.length} VALUES rows to scratchpad/wave2_values.sql`);
