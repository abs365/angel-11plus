    when 'QT-RC-01' then 'RC-01' when 'QT-RC-02' then 'RC-02' when 'QT-RC-03' then 'RC-03'
    when 'QT-RC-04' then 'RC-03' when 'QT-RC-05' then 'RC-02' when 'QT-RC-06' then 'RC-04'
    when 'QT-RC-07' then 'RC-01' when 'QT-RC-08' then 'RC-01' when 'QT-RC-09' then 'RC-01'
    when 'QT-RC-10' then 'RC-02' when 'QT-AR-01' then 'AR-01'
    when 'QT-WC-01a' then 'WC-01' when 'QT-WC-01b' then 'WC-01'
    when 'QT-MR-01' then 'MR-01' when 'QT-MR-02' then 'MR-01' when 'QT-MR-03' then 'MR-01'
    when 'QT-MR-04' then 'MR-04' when 'QT-MR-05' then 'MR-02' when 'QT-MR-06' then 'MR-02'
    when 'QT-MR-07' then 'MR-03' when 'QT-MR-08' then 'MR-03' when 'QT-MR-09' then 'MR-01'
    when 'QT-MR-10' then 'MR-04' when 'QT-MR-11' then 'MR-05' when 'QT-MR-12' then 'MR-01'
    when 'QT-MR-13' then 'MR-04' when 'QT-MR-14' then 'MR-06'
