-- === Trigger function redefined: analysis runs immediately after a
-- successful score, in its own isolated exception block =================

create or replace function public.mock_attempt_report_init()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'submitted' and (old.status is distinct from 'submitted') then
    insert into public.ali_mock_attempt_report (attempt_id)
    values (new.id)
    on conflict (attempt_id) do nothing;

    begin
      perform public.mock_score_attempt(new.id);
    exception when others then
      update public.ali_mock_attempt_report
      set scoring_state = 'failed', updated_at = now()
      where attempt_id = new.id;
    end;

    -- Decision 223 -- entirely independent nested block. Only proceeds
    -- once scoring genuinely, freshly succeeded (re-read from the row,
    -- never assumed); an analysis failure here touches analysis_state
    -- only, never scoring_state/question_outcomes/overall, and can
    -- never affect the learner's own already-committed submission.
    begin
      if (select scoring_state from public.ali_mock_attempt_report where attempt_id = new.id) = 'scored' then
        perform public.mock_analyse_attempt(new.id);
      end if;
    exception when others then
      update public.ali_mock_attempt_report
      set analysis_state = 'failed', updated_at = now()
      where attempt_id = new.id;
    end;
  end if;
  return new;
end;
